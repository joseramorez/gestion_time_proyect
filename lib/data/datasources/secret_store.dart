import 'package:flutter_secure_storage/flutter_secure_storage.dart';

/// Almacén de secretos (Client Secret, tokens). En la app real usa el
/// almacén del sistema operativo; en pruebas se sustituye por uno en memoria.
abstract class SecretStore {
  Future<String?> read(String key);
  Future<void> write(String key, String value);
  Future<void> delete(String key);
}

class SecureSecretStore implements SecretStore {
  const SecureSecretStore();

  // macOS: sin el keychain de protección de datos no hace falta el entitlement
  // "Keychain Sharing", que exige una cuenta de desarrollador con aprovisionamiento.
  static const _storage = FlutterSecureStorage(
    mOptions: MacOsOptions(usesDataProtectionKeychain: false),
  );

  @override
  Future<String?> read(String key) => _storage.read(key: key);

  @override
  Future<void> write(String key, String value) =>
      _storage.write(key: key, value: value);

  @override
  Future<void> delete(String key) => _storage.delete(key: key);
}

class MemorySecretStore implements SecretStore {
  final Map<String, String> data = {};

  @override
  Future<String?> read(String key) async => data[key];

  @override
  Future<void> write(String key, String value) async => data[key] = value;

  @override
  Future<void> delete(String key) async => data.remove(key);
}
